"""Centre-line alphabet shared by every font. Units: 1000 per em, y up, baseline 0.

Cap height 700, x-height 500, ascender 730, descender -200. A glyph is {"strokes": [[(x, y), ...], ...],
"dots": [(x, y), ...]}; each style turns the centre lines into outlines in its own way.
"""
import math

CAP, XH, ASC, DESC = 700, 500, 730, -200


def P(*pts):
    return [(float(x), float(y)) for x, y in pts]


def arc(cx, cy, rx, ry, a0, a1, step=5):
    n = max(6, int(abs(a1 - a0) / step))
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def spline(*pts, per=12):
    """Catmull-Rom curve through the points (ends repeated), as a dense polyline."""
    pts = [(float(x), float(y)) for x, y in pts]
    q = [pts[0]] + pts + [pts[-1]]
    out = []
    for i in range(1, len(q) - 2):
        p0, p1, p2, p3 = q[i - 1], q[i], q[i + 1], q[i + 2]
        for k in range(per):
            t = k / per
            t2, t3 = t * t, t * t * t
            out.append(tuple(0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                                    + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3) for j in (0, 1)))
    out.append(pts[-1])
    return out


def cat(*parts):
    out = []
    for part in parts:
        for p in part:
            if not out or math.hypot(p[0] - out[-1][0], p[1] - out[-1][1]) > 1e-6:
                out.append(p)
    return out


def ell(cx, cy, rx, ry):
    return arc(cx, cy, rx, ry, 90, 450)  # closed, starting at the top


def sshape(w, h, y0=0):
    """An S across w by h, from the top right to the bottom left."""
    pts = [(.93, .86), (.74, .98), (.50, 1.0), (.24, .96), (.08, .82), (.12, .66), (.32, .54), (.55, .46), (.80, .38),
           (.93, .22), (.86, .08), (.62, .0), (.36, .0), (.14, .07), (.03, .18)]
    return spline(*[(w * x, y0 + h * y) for x, y in pts], per=10)


