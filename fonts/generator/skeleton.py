def classes(ch):
    """Spacing class: round, diagonal, straight, open, or mark."""
    if ch in "oOcCeGQ0dgqabpsS3689":
        return "round"
    if ch in "AVWXYvwxyTZ7/":
        return "diag"
    if ch in ".,:;!'\"|":
        return "mark"
    return "straight"
